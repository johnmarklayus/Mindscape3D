const contentPhrases = { ...navigation, ...phrases }

const phrasePattern = new RegExp(
  Object.keys(contentPhrases)
    .sort((a, b) => b.length - a.length)
    .map((value) => {
      const escaped = value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
      const start = /^[\p{L}\p{N}_]/u.test(value) ? "(?<![\\p{L}\\p{N}_])" : ""
      const end = /[\p{L}\p{N}_]$/u.test(value) ? "(?![\\p{L}\\p{N}_])" : ""
      return `${start}${escaped}${end}`
    })
    .join("|"),
  "gu",
)

function translatePlainText(value: string) {
  return value.replace(phrasePattern, (match) => contentPhrases[match] ?? match)
}

/** Translate prose while protecting fenced code, inline code, HTML tags, and link destinations. */
export function localizeMarkdown(markdown: string, language: Language) {
  if (language === "en") return markdown
  const protectedParts = /(```[\s\S]*?```|`[^`\n]+`|https?:\/\/[^\s)]+|<[^>\n]+>)/g
  return markdown
    .split(protectedParts)
    .map((part, index) => (index % 2 === 0 ? translatePlainText(part) : part))
    .join("")
}

export function localizeNavigation(value: string, language: Language) {
  if (language === "en") return value
  return navigation[value] ?? translatePlainText(value)
}

export function localizeText(value: string, language: Language) {
  return language === "en" ? value : translatePlainText(value)
}
